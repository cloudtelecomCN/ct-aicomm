import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
const schema = JSON.parse(await readFile(new URL("schemas/evidence/evidence-object-v1.schema.json", root), "utf8"));
const ajv = new Ajv2020({ code: { source: true }, allErrors: true, ownProperties: true, allowUnionTypes: true });
addFormats(ajv, ["date-time", "uri"]);

const built = await build({
  stdin: {
    contents: standaloneCode(ajv, ajv.compile(schema)),
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  format: "esm",
  write: false,
  metafile: true,
  charset: "utf8",
  minify: true,
});
const packages = [...new Set(Object.keys(built.metafile.inputs)
  .map((filename) => /^node_modules\/([^/]+)\//u.exec(filename)?.[1])
  .filter(Boolean))].sort();
const notices = await Promise.all(packages.map(async (name) => {
  const license = await readFile(new URL(`node_modules/${name}/LICENSE`, root), "utf8");
  return `/* ${name}\n${license.trim().replace(/\r\n/gu, "\n")}\n*/\n`;
}));
const source = "// Generated by npm run build:validator from the public Evidence Core schema.\n"
  + notices.join("") + built.outputFiles[0].text;
const destination = new URL("cli/evidence-schema.generated.mjs", root);
if (process.argv.includes("--check")) {
  assert.equal(await readFile(destination, "utf8"), source, "Run npm run build:validator after changing the Evidence Core schema.");
} else {
  await writeFile(destination, source);
}
